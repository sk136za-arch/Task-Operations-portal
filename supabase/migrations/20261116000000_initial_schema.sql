-- Task Operations Portal: initial PostgreSQL schema for Supabase.
-- Apply with `supabase db push` or paste into the Supabase SQL editor.

create table if not exists public.users (
  id text primary key,
  email text not null unique,
  display_name text not null,
  role text not null check (role in ('admin', 'editor', 'viewer')),
  active boolean not null default true,
  granted_by text,
  granted_at timestamptz not null,
  updated_at timestamptz not null
);

create table if not exists public.tasks (
  id bigint generated by default as identity primary key,
  task_id text not null unique,
  environment text not null,
  team text not null,
  service text not null,
  title text not null,
  start_date text,
  end_date text,
  uat_detail text not null default '',
  production_detail text not null default '',
  status text not null,
  remark text not null default '',
  revision integer not null default 1,
  created_at timestamptz not null,
  updated_at timestamptz not null,
  updated_by text not null
);

create table if not exists public.deployments (
  id bigint generated by default as identity primary key,
  task_id text not null,
  sprint text not null default '',
  environment text not null,
  type text not null check (type in ('uat', 'prod')),
  planned_date text,
  actual_date text,
  date_label text not null default '',
  detail text not null,
  result text not null default 'planned',
  created_at timestamptz not null,
  updated_at timestamptz not null
);

create index if not exists deployments_task_id_idx on public.deployments (task_id);

create table if not exists public.lookup_values (
  id bigint generated by default as identity primary key,
  kind text not null check (kind in ('environment', 'team', 'service', 'status', 'due_threshold')),
  value text not null,
  active boolean not null default true,
  sort_order integer not null default 0,
  unique (kind, value)
);

create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  actor_id text not null,
  actor_email text not null,
  action text not null,
  entity_type text not null,
  entity_id text not null,
  before_json text,
  after_json text,
  created_at timestamptz not null
);

create table if not exists public.import_runs (
  id bigint generated by default as identity primary key,
  source_id text not null,
  imported_by text not null,
  valid_tasks integer not null,
  deployments integer not null,
  warnings integer not null,
  duplicates integer not null,
  created_at timestamptz not null
);

