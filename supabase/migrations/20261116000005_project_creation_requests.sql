create table if not exists public.project_creation_requests (
  id bigint generated by default as identity primary key,
  requester_id text not null,
  requester_email text not null,
  requester_name text not null,
  name text not null,
  description text not null default '',
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  project_id uuid references public.projects(id),
  reviewed_by text,
  reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index if not exists project_creation_requests_one_pending on public.project_creation_requests(requester_email, name) where status = 'pending';
alter table public.project_creation_requests enable row level security;
grant all privileges on table public.project_creation_requests to service_role;

create or replace function public.approve_project_creation_request(p_request_id bigint, p_reviewer text)
returns uuid language plpgsql security definer set search_path = public as $$
declare r public.project_creation_requests; p_id uuid; base_slug text; candidate text; n integer := 0;
begin
  select * into r from public.project_creation_requests where id = p_request_id for update;
  if not found then raise exception 'Project creation request not found' using errcode='P0002'; end if;
  if r.status <> 'pending' then raise exception 'Project creation request has already been reviewed' using errcode='P0001'; end if;
  base_slug := trim(both '-' from regexp_replace(lower(r.name), '[^a-z0-9]+', '-', 'g'));
  if base_slug = '' then base_slug := 'project'; end if;
  candidate := base_slug;
  while exists(select 1 from public.projects where slug=candidate) loop n := n + 1; candidate := base_slug || '-' || n; end loop;
  insert into public.projects(slug,name,description,active,created_by) values(candidate,r.name,r.description,true,r.requester_email) returning id into p_id;
  insert into public.project_members(project_id,user_id,email,display_name,role,active,granted_by) values(p_id,r.requester_id,r.requester_email,r.requester_name,'admin',true,p_reviewer);
  update public.project_creation_requests set status='approved',project_id=p_id,reviewed_by=p_reviewer,reviewed_at=now(),updated_at=now() where id=p_request_id;
  return p_id;
end $$;
revoke all on function public.approve_project_creation_request(bigint,text) from public, anon, authenticated;
grant execute on function public.approve_project_creation_request(bigint,text) to service_role;
