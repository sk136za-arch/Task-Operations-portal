-- Keep task/deployment audit events durable without making the dashboard wait for
-- audit_logs indexes and notification-feed work on every mutation.

create table if not exists public.project_audit_outbox (
  id bigint generated by default as identity primary key,
  project_id uuid not null references public.projects(id) on delete cascade,
  actor_id text not null,
  actor_email text not null,
  action text not null,
  entity_type text not null check (entity_type in ('task', 'deployment')),
  entity_id text not null,
  before_json text,
  after_json text,
  created_at timestamptz not null default now(),
  processed_at timestamptz,
  attempts integer not null default 0 check (attempts >= 0)
);

create index if not exists project_audit_outbox_pending_idx
  on public.project_audit_outbox (created_at, id)
  where processed_at is null;

alter table public.audit_logs add column if not exists outbox_id bigint references public.project_audit_outbox(id) on delete set null;
create unique index if not exists audit_logs_outbox_id_unique
  on public.audit_logs (outbox_id) where outbox_id is not null;

alter table public.project_audit_outbox enable row level security;
grant all privileges on table public.project_audit_outbox to service_role;
grant usage, select on sequence public.project_audit_outbox_id_seq to service_role;

create or replace function public.enqueue_project_audit(
  p_project_id uuid, p_actor_id text, p_actor_email text, p_action text,
  p_entity_type text, p_entity_id text, p_before_json text, p_after_json text,
  p_created_at timestamptz default now()
) returns bigint
language plpgsql security definer set search_path = public as $$
declare
  v_outbox_id bigint;
begin
  if p_entity_type not in ('task', 'deployment') then
    raise exception 'Unsupported audit entity type' using errcode = '22023';
  end if;
  insert into public.project_audit_outbox(
    project_id, actor_id, actor_email, action, entity_type, entity_id,
    before_json, after_json, created_at
  ) values (
    p_project_id, p_actor_id, p_actor_email, p_action, p_entity_type, p_entity_id,
    p_before_json, p_after_json, p_created_at
  ) returning id into v_outbox_id;
  return v_outbox_id;
end $$;

-- A single transaction claims a bounded batch, materializes it once, then marks it
-- delivered. If it aborts, both audit_logs and processed_at roll back together.
create or replace function public.process_project_audit_outbox(p_limit integer default 100)
returns integer
language plpgsql security definer set search_path = public as $$
declare
  v_processed integer := 0;
begin
  if p_limit is null or p_limit < 1 or p_limit > 1000 then
    raise exception 'p_limit must be between 1 and 1000' using errcode = '22023';
  end if;

  with claimed as materialized (
    select id, project_id, actor_id, actor_email, action, entity_type, entity_id,
      before_json, after_json, created_at
    from public.project_audit_outbox
    where processed_at is null
    order by created_at, id
    for update skip locked
    limit p_limit
  ), materialized as (
    insert into public.audit_logs(
      outbox_id, project_id, actor_id, actor_email, action, entity_type, entity_id,
      before_json, after_json, created_at
    )
    select id, project_id, actor_id, actor_email, action, entity_type, entity_id,
      before_json, after_json, created_at
    from claimed
    on conflict (outbox_id) where outbox_id is not null do nothing
    returning outbox_id
  ), marked as (
    update public.project_audit_outbox queue
    set processed_at = now(), attempts = queue.attempts + 1
    from claimed
    where queue.id = claimed.id
    returning queue.id
  )
  select count(*) into v_processed from marked;

  return v_processed;
end $$;

-- All task/deployment writes below enqueue their event in the same transaction as
-- the business change. The scheduler can process it later without losing it.
create or replace function public.create_project_task(
  p_project_id uuid, p_task jsonb, p_actor_id text, p_actor_email text
) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_created public.tasks%rowtype;
  v_task_id text;
  v_now timestamptz := now();
begin
  insert into public.tasks(
    project_id, task_id, environment, team, service, title, start_date, end_date,
    uat_detail, production_detail, status, remark, revision, created_at, updated_at, updated_by
  ) values (
    p_project_id, 'AUTO-' || gen_random_uuid(), p_task->>'environment', p_task->>'team',
    p_task->>'service', p_task->>'title', p_task->>'startDate', p_task->>'endDate',
    coalesce(p_task->>'uatDetail', ''), coalesce(p_task->>'productionDetail', ''),
    p_task->>'status', coalesce(p_task->>'remark', ''), 1, v_now, v_now, p_actor_email
  ) returning * into v_created;
  v_task_id := 'BLS-' || lpad(v_created.id::text, 2, '0');
  update public.tasks set task_id = v_task_id where id = v_created.id returning * into v_created;
  perform public.enqueue_project_audit(
    p_project_id, p_actor_id, p_actor_email, 'create', 'task', v_task_id,
    null, to_jsonb(v_created)::text, v_now
  );
  return to_jsonb(v_created);
end $$;

create or replace function public.update_project_task(
  p_project_id uuid, p_task_id text, p_revision integer, p_task jsonb,
  p_actor_id text, p_actor_email text
) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_before public.tasks%rowtype;
  v_updated public.tasks%rowtype;
  v_next_status text := coalesce(p_task->>'status', '');
  v_now timestamptz := now();
begin
  select * into v_before from public.tasks where project_id = p_project_id and task_id = p_task_id for update;
  if not found then raise exception 'Task not found' using errcode = 'P0002'; end if;
  if v_before.revision <> p_revision then raise exception 'Task changed by another user' using errcode = '40001'; end if;
  if ((lower(trim(v_before.status)) <> 'deploy prod done' and lower(trim(v_next_status)) = 'deploy prod done') or (v_next_status ~* 'cancel' and v_before.status !~* 'cancel'))
    and exists(select 1 from public.deployments where project_id = p_project_id and task_id = p_task_id and result = 'planned') then
    raise exception 'Use the deployment transition workflow' using errcode = 'P0001';
  end if;
  update public.tasks set
    environment = p_task->>'environment', team = p_task->>'team', service = p_task->>'service', title = p_task->>'title',
    start_date = case when p_task ? 'startDate' then p_task->>'startDate' else v_before.start_date end,
    end_date = case when p_task ? 'endDate' then p_task->>'endDate' else v_before.end_date end,
    uat_detail = coalesce(p_task->>'uatDetail', ''), production_detail = coalesce(p_task->>'productionDetail', ''),
    status = v_next_status, remark = coalesce(p_task->>'remark', ''), revision = v_before.revision + 1,
    updated_at = v_now, updated_by = p_actor_email
  where project_id = p_project_id and task_id = p_task_id returning * into v_updated;
  perform public.enqueue_project_audit(p_project_id, p_actor_id, p_actor_email, 'update', 'task', p_task_id,
    to_jsonb(v_before)::text, to_jsonb(v_updated)::text, v_now);
  return to_jsonb(v_updated);
end $$;

create or replace function public.create_project_deployment(
  p_project_id uuid, p_task_id text, p_deployment jsonb, p_actor_id text, p_actor_email text
) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_task public.tasks%rowtype;
  v_created public.deployments%rowtype;
  v_now timestamptz := now();
begin
  select * into v_task from public.tasks where project_id = p_project_id and task_id = p_task_id for update;
  if not found then raise exception 'Task not found' using errcode = 'P0002'; end if;
  insert into public.deployments(
    project_id, task_id, sprint, environment, type, planned_date, actual_date,
    date_label, detail, result, created_at, updated_at
  ) values (
    p_project_id, p_task_id, coalesce(p_deployment->>'sprint', ''), p_deployment->>'environment',
    p_deployment->>'type', p_deployment->>'plannedDate', p_deployment->>'actualDate',
    coalesce(p_deployment->>'dateLabel', ''), p_deployment->>'detail',
    coalesce(p_deployment->>'result', 'planned'), v_now, v_now
  ) returning * into v_created;
  update public.tasks set updated_at = v_now, updated_by = p_actor_email where id = v_task.id;
  perform public.enqueue_project_audit(p_project_id, p_actor_id, p_actor_email, 'create', 'deployment', v_created.id::text,
    null, to_jsonb(v_created)::text, v_now);
  return to_jsonb(v_created);
end $$;

create or replace function public.update_project_deployment(
  p_project_id uuid, p_task_id text, p_deployment_id bigint, p_deployment jsonb,
  p_actor_id text, p_actor_email text
) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_before public.deployments%rowtype;
  v_updated public.deployments%rowtype;
  v_now timestamptz := now();
begin
  select * into v_before from public.deployments where project_id = p_project_id and id = p_deployment_id and task_id = p_task_id for update;
  if not found then raise exception 'Deployment not found' using errcode = 'P0002'; end if;
  update public.deployments set
    sprint = coalesce(p_deployment->>'sprint', ''), environment = p_deployment->>'environment', type = p_deployment->>'type',
    planned_date = case when p_deployment ? 'plannedDate' then p_deployment->>'plannedDate' else v_before.planned_date end,
    actual_date = case when p_deployment ? 'actualDate' then p_deployment->>'actualDate' else v_before.actual_date end,
    date_label = coalesce(p_deployment->>'dateLabel', ''), detail = p_deployment->>'detail',
    result = coalesce(p_deployment->>'result', 'planned'), updated_at = v_now
  where project_id = p_project_id and id = p_deployment_id returning * into v_updated;
  update public.tasks set updated_at = v_now, updated_by = p_actor_email where project_id = p_project_id and task_id = p_task_id;
  perform public.enqueue_project_audit(p_project_id, p_actor_id, p_actor_email, 'update', 'deployment', p_deployment_id::text,
    to_jsonb(v_before)::text, to_jsonb(v_updated)::text, v_now);
  return to_jsonb(v_updated);
end $$;

create or replace function public.delete_project_deployment(
  p_project_id uuid, p_task_id text, p_deployment_id bigint, p_actor_id text, p_actor_email text
) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_before public.deployments%rowtype;
  v_updated_task public.tasks%rowtype;
  v_now timestamptz := now();
begin
  select * into v_before from public.deployments
  where project_id = p_project_id and id = p_deployment_id and task_id = p_task_id for update;
  if not found then raise exception 'Deployment not found' using errcode = 'P0002'; end if;
  delete from public.deployments where id = v_before.id;
  update public.tasks set updated_at = v_now, updated_by = p_actor_email
  where project_id = p_project_id and task_id = p_task_id returning * into v_updated_task;
  perform public.enqueue_project_audit(p_project_id, p_actor_id, p_actor_email, 'delete', 'deployment', p_deployment_id::text,
    to_jsonb(v_before)::text, null, v_now);
  return to_jsonb(v_updated_task);
end $$;

create or replace function public.complete_project_production(
  p_project_id uuid, p_task_id text, p_revision integer, p_deployment_id bigint,
  p_mark_task_done boolean, p_actor_id text, p_actor_email text
) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_task public.tasks%rowtype;
  v_deployment public.deployments%rowtype;
  v_before_deployment public.deployments%rowtype;
  v_updated_task public.tasks%rowtype;
  v_now timestamptz := now();
begin
  select * into v_task from public.tasks where project_id = p_project_id and task_id = p_task_id for update;
  if not found then raise exception 'Task not found' using errcode = 'P0002'; end if;
  if v_task.revision <> p_revision then raise exception 'Task changed by another user' using errcode = '40001'; end if;
  if p_deployment_id is null then
    select * into v_deployment from public.deployments where project_id = p_project_id and task_id = p_task_id and result = 'planned' order by id limit 1 for update;
  else
    select * into v_deployment from public.deployments where project_id = p_project_id and task_id = p_task_id and id = p_deployment_id and result = 'planned' for update;
  end if;
  if not found then raise exception 'Selected deployment is no longer planned' using errcode = '40001'; end if;
  v_before_deployment := v_deployment;
  update public.deployments set result = 'success', updated_at = v_now where id = v_deployment.id returning * into v_deployment;
  update public.tasks set status = 'Deploy Prod Done', revision = revision + 1, updated_at = v_now, updated_by = p_actor_email
  where project_id = p_project_id and task_id = p_task_id and revision = p_revision returning * into v_updated_task;
  if not found then raise exception 'Task changed by another user' using errcode = '40001'; end if;
  perform public.enqueue_project_audit(p_project_id, p_actor_id, p_actor_email, 'complete-production', 'task', p_task_id,
    jsonb_build_object('task', to_jsonb(v_task), 'deployment', to_jsonb(v_before_deployment))::text,
    jsonb_build_object('task', to_jsonb(v_updated_task), 'deployment', to_jsonb(v_deployment))::text, v_now);
  return jsonb_build_object('task', to_jsonb(v_updated_task), 'deployment', to_jsonb(v_deployment), 'taskStatusChanged', true);
end $$;

create or replace function public.cancel_project_task_deployments(
  p_project_id uuid, p_task_id text, p_revision integer, p_scope text,
  p_deployment_id bigint, p_task_status text, p_actor_id text, p_actor_email text
) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_task public.tasks%rowtype;
  v_updated_task public.tasks%rowtype;
  v_deployment public.deployments%rowtype;
  v_before_deployment public.deployments%rowtype;
  v_cancelled_count integer := 0;
  v_before_deployments jsonb := '[]'::jsonb;
  v_after_deployments jsonb := '[]'::jsonb;
  v_now timestamptz := now();
begin
  if p_scope not in ('one', 'all') then raise exception 'Invalid cancellation scope' using errcode = '22023'; end if;
  if p_task_status !~* 'cancel' then raise exception 'Task status must be a cancellation status' using errcode = '22023'; end if;
  select * into v_task from public.tasks where project_id = p_project_id and task_id = p_task_id for update;
  if not found then raise exception 'Task not found' using errcode = 'P0002'; end if;
  if v_task.revision <> p_revision then raise exception 'Task changed by another user' using errcode = '40001'; end if;
  if p_scope = 'one' then
    if p_deployment_id is null then raise exception 'A deployment selection is required' using errcode = '22023'; end if;
    select * into v_deployment from public.deployments where project_id = p_project_id and task_id = p_task_id and id = p_deployment_id and result = 'planned' for update;
    if not found then raise exception 'Selected deployment is no longer planned' using errcode = '40001'; end if;
    v_before_deployment := v_deployment;
    update public.deployments set result = 'cancelled', updated_at = v_now where id = v_deployment.id returning * into v_deployment;
    v_cancelled_count := 1;
    v_before_deployments := jsonb_build_array(to_jsonb(v_before_deployment));
    v_after_deployments := jsonb_build_array(to_jsonb(v_deployment));
  else
    with locked_plans as (
      select id, to_jsonb(deployment) as before_snapshot from public.deployments deployment
      where project_id = p_project_id and task_id = p_task_id and result = 'planned' for update
    ), cancelled_plans as (
      update public.deployments deployment set result = 'cancelled', updated_at = v_now
      from locked_plans where deployment.id = locked_plans.id
      returning deployment.id, to_jsonb(deployment) as after_snapshot
    )
    select count(cancelled_plans.id), coalesce(jsonb_agg(locked_plans.before_snapshot), '[]'::jsonb), coalesce(jsonb_agg(cancelled_plans.after_snapshot), '[]'::jsonb)
    into v_cancelled_count, v_before_deployments, v_after_deployments
    from locked_plans left join cancelled_plans using (id);
    if v_cancelled_count = 0 then raise exception 'No planned deployment remains' using errcode = '40001'; end if;
  end if;
  update public.tasks set status = p_task_status, revision = revision + 1, updated_at = v_now, updated_by = p_actor_email
  where project_id = p_project_id and task_id = p_task_id and revision = p_revision returning * into v_updated_task;
  if not found then raise exception 'Task changed by another user' using errcode = '40001'; end if;
  perform public.enqueue_project_audit(p_project_id, p_actor_id, p_actor_email, 'cancel-deployments', 'task', p_task_id,
    jsonb_build_object('task', to_jsonb(v_task), 'scope', p_scope, 'deploymentId', p_deployment_id, 'deployments', v_before_deployments)::text,
    jsonb_build_object('task', to_jsonb(v_updated_task), 'cancelledDeploymentCount', v_cancelled_count, 'deployments', v_after_deployments)::text, v_now);
  return jsonb_build_object('task', to_jsonb(v_updated_task), 'deployments', v_after_deployments, 'cancelledDeploymentCount', v_cancelled_count);
end $$;

