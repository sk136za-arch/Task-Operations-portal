create table if not exists public.projects (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique,
  name text not null,
  description text not null default '',
  active boolean not null default true,
  created_by text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.project_members (
  id bigint generated by default as identity primary key,
  project_id uuid not null references public.projects(id) on delete cascade,
  user_id text not null,
  email text not null,
  display_name text not null,
  role text not null check (role in ('admin', 'editor', 'viewer')),
  active boolean not null default true,
  granted_by text not null,
  granted_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(project_id, email)
);

create table if not exists public.project_access_requests (
  id bigint generated by default as identity primary key,
  project_id uuid not null references public.projects(id) on delete cascade,
  user_id text not null,
  email text not null,
  display_name text not null,
  requested_role text not null default 'viewer' check (requested_role = 'viewer'),
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  reviewed_by text,
  reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index if not exists project_access_requests_one_pending on public.project_access_requests(project_id, email) where status = 'pending';

